#include "philo.h"

uint8_t	ft_strcmp(char *s1, char *s2)
{
	uint32_t	i;

	i = 0;
	while (s1[i] && s2[i])
	{
		if (s1[i] != s2[i])
			return (s1[i] - s2[i]);
		i++;
	}
	return (s1[i] - s2[i]);
}
